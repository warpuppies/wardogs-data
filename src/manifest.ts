import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { type GeneratedFile } from "./generated.js";

export const MANIFEST_PATH = "data/MANIFEST.json";

export const sha256 = (data: string | Uint8Array): string => createHash("sha256").update(data).digest("hex");

const Provenance = z.object({
  /** Steam build id the data was extracted from. */
  gameBuild: z.string(),
  /** CUE4Parse revision used by the extractor. */
  cue4parse: z.string(),
});
export type Provenance = z.infer<typeof Provenance>;

export const Manifest = z.object({
  schemaVersion: z.literal(1),
  generatedBy: z.literal("pnpm apply"),
  doNotEdit: z.literal(true),
  provenance: Provenance,
  files: z.array(z.object({ path: z.string(), sha256: z.string().length(64), bytes: z.number().int().nonnegative() })),
});
export type Manifest = z.infer<typeof Manifest>;

/** Builds the manifest for a set of generated files. The manifest does not list itself. */
export function buildManifest(files: readonly GeneratedFile[], provenance: Provenance): GeneratedFile {
  const manifest: Manifest = {
    schemaVersion: 1,
    generatedBy: "pnpm apply",
    doNotEdit: true,
    provenance,
    files: files
      .filter((f) => f.path !== MANIFEST_PATH)
      .map((f) => ({ path: f.path, sha256: sha256(f.content), bytes: Buffer.byteLength(f.content) }))
      .sort((a, b) => a.path.localeCompare(b.path)),
  };
  return { path: MANIFEST_PATH, content: JSON.stringify(manifest, null, 2) + "\n" };
}

export interface VerifyResult {
  ok: boolean;
  problems: string[];
  checked: number;
}

/**
 * Checks committed data against the manifest. Needs neither the game nor the cache, so it runs in CI.
 * It catches hand edits (checksum mismatch), deleted files, and files that the manifest does not list.
 */
export function verifyManifest(root: string, listDataFiles: (root: string) => string[]): VerifyResult {
  const problems: string[] = [];
  const manifestFile = join(root, MANIFEST_PATH);
  if (!existsSync(manifestFile)) return { ok: false, problems: [`${MANIFEST_PATH} is missing; run \`pnpm apply\`.`], checked: 0 };

  const manifest = Manifest.parse(JSON.parse(readFileSync(manifestFile, "utf8")));
  const listed = new Set(manifest.files.map((f) => f.path));
  for (const entry of manifest.files) {
    const full = join(root, entry.path);
    if (!existsSync(full)) problems.push(`missing: ${entry.path}`);
    else if (sha256(readFileSync(full)) !== entry.sha256) problems.push(`modified by hand or stale: ${entry.path}`);
  }
  for (const path of listDataFiles(root)) {
    if (path !== MANIFEST_PATH && !listed.has(path)) problems.push(`not generated by the pipeline: ${path}`);
  }
  return { ok: problems.length === 0, problems, checked: manifest.files.length };
}
