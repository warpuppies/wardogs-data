import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { walk } from "./generated.js";
import { hashFile } from "./maps/tiles.js";
import { BuildablesFile, VehiclesFile } from "./schema.gameplay.js";
import { ItemsFile } from "./schema.js";

export interface IconFile {
  /** Path relative to the release's `icons/` folder, as written in `items.json`. */
  path: string;
  sha256: string;
  bytes: number;
}

/**
 * Copies the icons that the data refers to from the extraction cache into `outDir` (cleared first), keeping their
 * folder structure, and returns each file with its checksum. The PNGs are copied as extracted, so the checksums
 * follow the game build. A referenced icon missing from the cache is an error: the data would point at nothing.
 */
export function copyIcons(iconsDir: string, outDir: string, referenced: Iterable<string | undefined>): IconFile[] {
  const paths = [...new Set([...referenced].filter((p): p is string => p !== undefined))].sort();
  const missing = paths.filter((p) => !existsSync(join(iconsDir, p)));
  if (missing.length) throw new Error(`${missing.length} icons referenced by the data are not in the cache (run \`pnpm extract items\`): ${missing.slice(0, 3).join(", ")}`);

  rmSync(outDir, { recursive: true, force: true });
  return paths.map((path) => {
    const dest = join(outDir, path);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(join(iconsDir, path), dest);
    return { path, sha256: hashFile(dest), bytes: statSync(dest).size };
  });
}

/** Every icon the published data names: the items', the buildables' and the vehicle weapons'. Needs only `data/`. */
export function iconReferences(root: string): string[] {
  const read = (file: string): unknown => JSON.parse(readFileSync(join(root, "data", file), "utf8"));
  return [
    ...ItemsFile.parse(read("items.json")).items.map((i) => i.icon),
    ...BuildablesFile.parse(read("buildables.json")).buildables.map((b) => b.icon),
    ...VehiclesFile.parse(read("vehicles.json")).vehicles.flatMap((v) => Object.values(v.weaponIcons ?? {})),
  ].filter((p): p is string => p !== undefined);
}

/** Item icons as named by `icon` in `items.json`. The images are kept out of git (ignored); the folder is built by `pnpm icons` and shipped in the full zip. */
export const TRACKED_ICONS_DIR = "assets/icons";
/** Their checksums. Plain text in git, so the manifest is checked even where the images are absent. */
export const TRACKED_ICONS_MANIFEST = "assets/icons.manifest.json";

const TrackedIcons = z.object({
  schemaVersion: z.literal(1),
  generatedBy: z.literal("pnpm icons"),
  doNotEdit: z.literal(true),
  files: z.array(z.object({ path: z.string(), sha256: z.string().length(64), bytes: z.number().int().nonnegative() })),
});

/** Writes the referenced icons to `assets/icons/` and their checksums to `assets/icons.manifest.json`. Idempotent. */
export function syncTrackedIcons(root: string, iconsDir: string, referenced: Iterable<string | undefined>): IconFile[] {
  const files = copyIcons(iconsDir, join(root, TRACKED_ICONS_DIR), referenced);
  const manifest: z.infer<typeof TrackedIcons> = { schemaVersion: 1, generatedBy: "pnpm icons", doNotEdit: true, files };
  writeFileSync(join(root, TRACKED_ICONS_MANIFEST), JSON.stringify(manifest, null, 2) + "\n");
  return files;
}

/**
 * Checks `assets/icons/` against its manifest and against the icons the data names (`iconReferences`): every referenced icon is listed, every listed
 * file exists with its size and checksum, and nothing else is in the folder. Needs no game. Returns the problems.
 */
export function verifyTrackedIcons(root: string, referenced: Iterable<string | undefined>): string[] {
  const manifestFile = join(root, TRACKED_ICONS_MANIFEST);
  if (!existsSync(manifestFile)) return [`${TRACKED_ICONS_MANIFEST} is missing; run \`pnpm icons\`.`];
  const manifest = TrackedIcons.parse(JSON.parse(readFileSync(manifestFile, "utf8")));
  const problems: string[] = [];
  const listed = new Set(manifest.files.map((f) => f.path));
  for (const path of new Set(referenced)) {
    if (path !== undefined && !listed.has(path)) problems.push(`named by the data but not tracked: ${path}`);
  }
  for (const f of manifest.files) {
    const full = join(root, TRACKED_ICONS_DIR, f.path);
    if (!existsSync(full)) problems.push(`missing: ${TRACKED_ICONS_DIR}/${f.path}`);
    else if (statSync(full).size !== f.bytes) problems.push(`size differs: ${TRACKED_ICONS_DIR}/${f.path}`);
    else if (hashFile(full) !== f.sha256) problems.push(`modified by hand or stale: ${TRACKED_ICONS_DIR}/${f.path}`);
  }
  for (const rel of walk(join(root, TRACKED_ICONS_DIR))) {
    if (!listed.has(rel)) problems.push(`not generated by the pipeline: ${TRACKED_ICONS_DIR}/${rel}`);
  }
  return problems;
}
