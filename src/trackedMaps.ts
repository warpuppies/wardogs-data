import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { walk } from "./generated.js";
import { hashFile } from "./maps/tiles.js";
import { readReleaseManifest } from "./release.js";

/** Map tiles and heightmaps, one folder per world. The files are kept out of git (ignored); the folder is built by `pnpm maps` and shipped in the full zip. */
export const TRACKED_MAPS_DIR = "assets/maps";
/** Their checksums. Plain text in git, so the manifest is checked even where the files are absent. */
export const TRACKED_MAPS_MANIFEST = "assets/maps.manifest.json";

const AssetFile = z.object({ path: z.string(), sha256: z.string().length(64), bytes: z.number().int().nonnegative() });
const TrackedMaps = z.object({
  schemaVersion: z.literal(1),
  generatedBy: z.literal("pnpm maps"),
  doNotEdit: z.literal(true),
  gameBuild: z.string(),
  worlds: z.record(z.string(), z.object({ sourceSha256: z.string(), maxZoom: z.number().int(), files: z.array(AssetFile), heightmap: AssetFile })),
});

/** Every file a world's manifest entry lists, tiles first, as paths relative to the world's folder. */
const listed = (world: z.infer<typeof TrackedMaps>["worlds"][string]) => [...world.files, world.heightmap];

/**
 * Copies the tiles and heightmaps that `dist/RELEASE-MANIFEST.json` lists (built by `pnpm assets`) into `assets/maps/`
 * and writes their checksums to `assets/maps.manifest.json`. Files that are no longer listed are removed. Idempotent:
 * a file that is already there with the right size and checksum is not copied again.
 */
export function syncTrackedMaps(root: string, distDir: string): { worlds: number; files: number } {
  const release = readReleaseManifest(distDir);
  const out = join(root, TRACKED_MAPS_DIR);
  const worlds: z.infer<typeof TrackedMaps>["worlds"] = {};
  let files = 0;
  for (const [id, world] of Object.entries(release.worlds).sort(([a], [b]) => a.localeCompare(b))) {
    worlds[id] = { sourceSha256: world.sourceSha256, maxZoom: world.maxZoom, files: world.files, heightmap: world.heightmap };
    const keep = new Set(listed(world).map((f) => f.path));
    for (const rel of walk(join(out, id))) if (!keep.has(rel)) rmSync(join(out, id, rel));
    for (const f of listed(world)) {
      const from = join(distDir, "maps", id, f.path);
      const to = join(out, id, f.path);
      if (!existsSync(from)) throw new Error(`${from} is listed in the release manifest but missing; run \`pnpm assets\``);
      if (!(existsSync(to) && statSync(to).size === f.bytes && hashFile(to) === f.sha256)) {
        mkdirSync(dirname(to), { recursive: true });
        copyFileSync(from, to);
      }
      files++;
    }
  }
  for (const entry of existsSync(out) ? [...new Set([...walk(out)].map((rel) => rel.split("/")[0]!))] : []) if (!(entry in worlds)) rmSync(join(out, entry), { recursive: true });
  writeFileSync(join(root, TRACKED_MAPS_MANIFEST), JSON.stringify({ schemaVersion: 1, generatedBy: "pnpm maps", doNotEdit: true, gameBuild: release.gameBuild, worlds }, null, 2) + "\n");
  return { worlds: Object.keys(worlds).length, files };
}

/**
 * Checks `assets/maps/` against its manifest: every listed file exists with its size and checksum, and nothing else is in
 * the folder. Needs no game. Returns the problems.
 */
export function verifyTrackedMaps(root: string): string[] {
  const manifestFile = join(root, TRACKED_MAPS_MANIFEST);
  if (!existsSync(manifestFile)) return [`${TRACKED_MAPS_MANIFEST} is missing; run \`pnpm maps\`.`];
  const manifest = TrackedMaps.parse(JSON.parse(readFileSync(manifestFile, "utf8")));
  const problems: string[] = [];
  const known = new Set<string>();
  for (const [id, world] of Object.entries(manifest.worlds)) {
    for (const f of listed(world)) {
      known.add(`${id}/${f.path}`);
      const full = join(root, TRACKED_MAPS_DIR, id, f.path);
      const label = `${TRACKED_MAPS_DIR}/${id}/${f.path}`;
      if (!existsSync(full)) problems.push(`missing: ${label}`);
      else if (statSync(full).size !== f.bytes) problems.push(`size differs: ${label}`);
      else if (hashFile(full) !== f.sha256) problems.push(`modified by hand or stale: ${label}`);
    }
  }
  for (const rel of walk(join(root, TRACKED_MAPS_DIR))) if (!known.has(rel)) problems.push(`not generated by the pipeline: ${TRACKED_MAPS_DIR}/${rel}`);
  return problems;
}
