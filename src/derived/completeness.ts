const LABEL: Record<Completeness, string> = { complete: "Complete", partial: "Partial", unavailable: "Not in the game files" };

const code = (text: string): string => `\`${text}\``;

/** The completeness table as Markdown, the same text in the dictionary and in the README. */
export function completenessTable(): string {
  return [
    "| Area | Status | Files | Missing or uncertain |",
    "| --- | --- | --- | --- |",
    ...COMPLETENESS.map((a) => `| ${a.area} | ${LABEL[a.status]} | ${a.files.length ? a.files.map(code).join("<br>") : "-"} | ${a.notes || "-"} |`),
  ].join("\n");
}

export const COMPLETENESS_START = "<!-- completeness:start (generated by `pnpm readme`) -->";
export const COMPLETENESS_END = "<!-- completeness:end -->";

/** Replaces the text between the completeness markers in a Markdown document. Throws when a marker is missing. */
export function withCompleteness(markdown: string): string {
  const start = markdown.indexOf(COMPLETENESS_START);
  const end = markdown.indexOf(COMPLETENESS_END);
  if (start < 0 || end < start) throw new Error("The completeness markers are missing from the document.");
  return `${markdown.slice(0, start + COMPLETENESS_START.length)}\n\n${completenessTable()}\n\n${markdown.slice(end)}`;
}
