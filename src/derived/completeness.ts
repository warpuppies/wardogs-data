export type Completeness = "complete" | "partial" | "unavailable";

export interface Area {
  area: string;
  status: Completeness;
  /** Published files for the area, as paths under `data/` (`maps/<world>/...` for per-world files). Empty when there are none. */
  files: readonly string[];
  /** What is missing or uncertain. */
  notes: string;
}

