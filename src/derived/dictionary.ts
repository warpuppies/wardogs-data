import type { CsvTable } from "./csv.js";
import { completenessTable } from "./completeness.js";
import { fieldDocs, jsonSchemaFor, PUBLISHED, schemaPath } from "./schemas.js";

/** Paths of every file in a published set, by schema name, sorted. */
const filesFor = (name: string, paths: readonly string[]): string[] => {
  const entry = PUBLISHED.find((p) => p.name === name)!;
  return paths.filter((p) => entry.match.test(p)).sort();
};

const escape = (text: string): string => text.replaceAll("|", "\\|").replace(/\s*\n\s*/g, " ");
const code = (text: string): string => `\`${text.replaceAll("`", "'")}\``;

/** Conventions that hold for every file. Written here, with the data, so they cannot drift. */
const CONVENTIONS = [
  "**Units.** Distances are meters, speeds meters per second, mass kilograms, angles degrees, time seconds. The game stores centimeters; the single conversion is divide by 100, applied when the data is built. Files with a `units` field say so; fields with a unit in their name (`massKg`, `diameterMm`, `max_speed_kmh`) keep it.",
  "**Ids.** Item and vehicle ids are the game's own tags (`Id.Item.AK74M`, `Vehicle.Variant.Air.Rotary.Havoc.Default`). The game compares tags without regard to case, and its own data is not consistent (`Id.Item.SKSBarrel` and `ID.Item.SKSBarrel` both occur), so compare ids case-insensitively. Every other file refers to items by these ids.",
  "**Coordinates.** One system per world: X and Y on the ground, Z up, in meters. A map image pixel is `(world - bounds.min) / metersPerPixel`, and image rows increase with world Y. Each world has its own `bounds`, and the terrain heightmap has its own bounds and `zRange`, so use each file's own values.",
  "**Versions.** Every file records the Steam `gameBuild` it came from and a `schemaVersion`. A game update shows up as a diff of these files.",
  "**Developer items.** The game ships a few items for development (test and debug). They stay in the data, flagged `developer: true` in `items.json`; join on that flag to leave them out of weapons, ammunition and other files that refer to items.",
  "**Absent fields.** An optional field that is not in a record means the game does not define it. It is never filled with a default.",
  "**Generated.** Everything under `data/` is written by `pnpm apply`; do not edit it by hand. `pnpm verify` checks every file against `MANIFEST.json`.",
];

/**
 * The data dictionary: what every file holds and what every field means. Built from the same schemas that validate
 * the data and from the CSV column definitions, so it cannot disagree with them.
 */
export function buildDictionary(paths: readonly string[], csv: readonly CsvTable[], gameBuild: string): string {
  const out: string[] = [];
  out.push("# Data dictionary", "");
  out.push(`Generated by \`pnpm apply\` from the schemas and the data. Do not edit. Game build ${gameBuild}.`, "");
  out.push("## Conventions", "", ...CONVENTIONS.map((c) => `- ${c}`), "");

  out.push("## Completeness", "", "How much of the game each part of the data covers, and what is missing or uncertain.", "", completenessTable(), "");

  out.push("## Files", "", "| Data | Files | JSON Schema | CSV |", "| --- | --- | --- | --- |");
  for (const entry of PUBLISHED) {
    const files = filesFor(entry.name, paths);
    if (files.length === 0) continue;
    const tables = csv.filter((t) => t.path.startsWith(`data/csv/${entry.name}`) || (entry.name === "items" && t.path === "data/csv/prices.csv") || (entry.name === "weapons" && (t.path === "data/csv/weapon-slots.csv" || t.path === "data/csv/weapon-damage.csv" || t.path === "data/csv/weapon-compatibility.csv")) || (entry.name === "attachments" && t.path === "data/csv/attachment-modifiers.csv") || (entry.name === "equipment" && (t.path === "data/csv/armor.csv" || t.path === "data/csv/equipment-modifiers.csv" || t.path === "data/csv/weight-classes.csv")) || (entry.name === "tags" && t.path === "data/csv/tags.csv") || (entry.name === "cosmetics" && t.path === "data/csv/cosmetics.csv") || (entry.name === "buildables" && t.path === "data/csv/buildables.csv") || (entry.name === "loot" && t.path.startsWith("data/csv/loot-")) || (entry.name === "objectives" && t.path === "data/csv/control-zones.csv") || (entry.name === "objects" && t.path.startsWith("data/csv/objects-")) || (entry.name === "skills" && t.path.startsWith("data/csv/skill")) || (entry.name === "roles" && t.path === "data/csv/role-levels.csv") || (entry.name === "meta" && (t.path === "data/csv/gold-market.csv" || t.path === "data/csv/passive-missions.csv" || t.path === "data/csv/achievements.csv")) || (entry.name === "challenge-rewards" && (t.path.startsWith("data/csv/challenge-reward") || t.path === "data/csv/reward-curve-points.csv")) || (entry.name === "rewards" && t.path.startsWith("data/csv/reward")) || (entry.name === "damage" && t.path.startsWith("data/csv/damage-")) || (entry.name === "damage" && t.path === "data/csv/hit-location-multipliers.csv"));
    out.push(`| ${entry.title} | ${files.map(code).join("<br>")} | ${code(schemaPath(entry.name))} | ${tables.map((t) => code(t.path)).join("<br>") || "-"} |`);
  }
  const extra = paths.filter((p) => /\.geojson$/.test(p)).sort();
  if (extra.length) out.push(`| Building footprints (GeoJSON, same buildings as the box files; \`height\` and \`baseZ\` in meters) | ${extra.map(code).join("<br>")} | - | - |`);
  out.push("");

  for (const entry of PUBLISHED) {
    const files = filesFor(entry.name, paths);
    if (files.length === 0) continue;
    const schema = jsonSchemaFor(entry) as { description?: string };
    out.push(`## ${entry.title}`, "");
    out.push(`Files: ${files.map(code).join(", ")}.`, "");
    if (schema.description) out.push(escape(schema.description), "");
    out.push("| Field | Type | Required | Description |", "| --- | --- | --- | --- |");
    for (const f of fieldDocs(jsonSchemaFor(entry))) {
      out.push(`| ${code(f.path)} | ${escape(f.type)} | ${f.required ? "yes" : "no"} | ${escape(f.description)} |`);
    }
    out.push("");
  }

  out.push("## CSV tables", "", "Flat copies of the data for spreadsheets. The first row is the header, cells are comma separated with RFC 4180 quoting, and empty means absent. Lists inside a cell are separated by `;`.", "");
  for (const t of csv) {
    out.push(`### ${code(t.path)}`, "", t.about, "", "| Column | Meaning |", "| --- | --- |");
    for (const c of t.columns) out.push(`| ${code(c.name)} | ${escape(c.about)} |`);
    out.push("");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}
