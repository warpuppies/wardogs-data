import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { copyIcons, iconReferences, syncTrackedIcons, TRACKED_ICONS_DIR, TRACKED_ICONS_MANIFEST, verifyTrackedIcons } from "../src/icons.js";
import { sha256 } from "../src/manifest.js";

const cache = () => {
  const dir = mkdtempSync(join(tmpdir(), "icons-"));
  const put = (path: string, content: string) => {
    mkdirSync(join(dir, "cache", path, ".."), { recursive: true });
    writeFileSync(join(dir, "cache", path), content);
  };
  return { cacheDir: join(dir, "cache"), outDir: join(dir, "out"), put };
};

describe("copyIcons", () => {
  it("copies each referenced icon once, keeps folders, and records checksums", () => {
    const { cacheDir, outDir, put } = cache();
    put("UI/A/T_One.png", "one");
    put("UI/B/T_Two.png", "two!");
    put("UI/B/T_Unused.png", "unused");
    const files = copyIcons(cacheDir, outDir, ["UI/B/T_Two.png", "UI/A/T_One.png", undefined, "UI/A/T_One.png"]);
    expect(files).toEqual([
      { path: "UI/A/T_One.png", sha256: sha256(Buffer.from("one")), bytes: 3 },
      { path: "UI/B/T_Two.png", sha256: sha256(Buffer.from("two!")), bytes: 4 },
    ]);
    expect(readFileSync(join(outDir, "UI/B/T_Two.png"), "utf8")).toBe("two!");
    expect(existsSync(join(outDir, "UI/B/T_Unused.png"))).toBe(false);
  });

  it("clears stale files from an earlier release", () => {
    const { cacheDir, outDir, put } = cache();
    put("T_Old.png", "old");
    put("T_New.png", "new");
    copyIcons(cacheDir, outDir, ["T_Old.png"]);
    copyIcons(cacheDir, outDir, ["T_New.png"]);
    expect(existsSync(join(outDir, "T_Old.png"))).toBe(false);
    expect(existsSync(join(outDir, "T_New.png"))).toBe(true);
  });

  it("fails when data points at an icon that was not extracted", () => {
    const { cacheDir, outDir, put } = cache();
    put("T_Here.png", "x");
    expect(() => copyIcons(cacheDir, outDir, ["T_Here.png", "T_Gone.png"])).toThrow(/T_Gone\.png/);
  });
});

describe("tracked icons", () => {
  const setup = () => {
    const { cacheDir, outDir, put } = cache();
    put("UI/A/T_One.png", "one");
    put("UI/B/T_Two.png", "two!");
    return { cacheDir, root: join(outDir, ".."), put };
  };

  it("syncs the referenced icons and verifies clean, twice over", () => {
    const { cacheDir, root } = setup();
    const files = syncTrackedIcons(root, cacheDir, ["UI/A/T_One.png", "UI/B/T_Two.png"]);
    expect(files.map((f) => f.path)).toEqual(["UI/A/T_One.png", "UI/B/T_Two.png"]);
    expect(verifyTrackedIcons(root, ["UI/A/T_One.png", undefined])).toEqual([]);
    const manifest = readFileSync(join(root, TRACKED_ICONS_MANIFEST), "utf8");
    syncTrackedIcons(root, cacheDir, ["UI/A/T_One.png", "UI/B/T_Two.png"]);
    expect(readFileSync(join(root, TRACKED_ICONS_MANIFEST), "utf8")).toBe(manifest);
  });

  it("reports a missing manifest, a hand edit, an extra file and an unlisted reference", () => {
    const { cacheDir, root } = setup();
    expect(verifyTrackedIcons(root, [])).toEqual([expect.stringContaining("missing")]);
    syncTrackedIcons(root, cacheDir, ["UI/A/T_One.png"]);
    writeFileSync(join(root, TRACKED_ICONS_DIR, "UI/A/T_One.png"), "ONE");
    writeFileSync(join(root, TRACKED_ICONS_DIR, "T_Extra.png"), "x");
    const problems = verifyTrackedIcons(root, ["UI/A/T_One.png", "UI/B/T_Two.png"]);
    expect(problems).toEqual(
      expect.arrayContaining([
        expect.stringContaining("named by the data but not tracked: UI/B/T_Two.png"),
        expect.stringContaining("modified by hand or stale: assets/icons/UI/A/T_One.png"),
        expect.stringContaining("not generated by the pipeline: assets/icons/T_Extra.png"),
      ]),
    );
  });
});

describe("iconReferences", () => {
  it("lists the icons the items, buildables and vehicle weapons name, and no others", () => {
    const refs = iconReferences(".");
    expect(refs).toContain("Buildables/Data/Buildables/SandbagWall/T_UI_Buildable_SandbagWall.png");
    expect(refs).toContain("UI/Shared/Icons/Vehicles/3D/T_UI_Vehicle_WPN_RocketPod.png");
    expect(refs.every((r) => r.endsWith(".png"))).toBe(true);
  });
});
