import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { hashFile } from "../src/maps/tiles.js";
import { syncTrackedMaps, TRACKED_MAPS_DIR, TRACKED_MAPS_MANIFEST, verifyTrackedMaps } from "../src/trackedMaps.js";

function put(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

/** A repo root and a dist/ with two worlds: tiles, a heightmap, and the release manifest that lists them. */
function setup() {
  const root = mkdtempSync(join(tmpdir(), "wardogs-maps-"));
  const dist = join(root, "dist");
  const entry = (world: string, path: string, content: string) => {
    put(join(dist, "maps", world, path), content);
    return { path, sha256: hashFile(join(dist, "maps", world, path)), bytes: content.length };
  };
  const worlds = {
    b: { sourceSha256: "sb", maxZoom: 1, files: [entry("b", "tiles/0/0/0.webp", "tile-b")], heightmap: entry("b", "heightmap.png", "height-b") },
    a: { sourceSha256: "sa", maxZoom: 1, files: [entry("a", "tiles/0/0/0.webp", "tile-a1"), entry("a", "tiles/1/0/0.webp", "tile-a2")], heightmap: entry("a", "heightmap.png", "height-a") },
  };
  put(join(dist, "RELEASE-MANIFEST.json"), JSON.stringify({ schemaVersion: 1, gameBuild: "9", cue4parse: "x", worlds, icons: [] }));
  return { root, dist };
}

describe("syncTrackedMaps", () => {
  it("copies every listed file under its world, writes a sorted manifest, and counts them", () => {
    const { root, dist } = setup();
    expect(syncTrackedMaps(root, dist)).toEqual({ worlds: 2, files: 5 });
    expect(readFileSync(join(root, TRACKED_MAPS_DIR, "a/tiles/1/0/0.webp"), "utf8")).toBe("tile-a2");
    const manifest = JSON.parse(readFileSync(join(root, TRACKED_MAPS_MANIFEST), "utf8"));
    expect(Object.keys(manifest.worlds)).toEqual(["a", "b"]);
    expect(manifest).toMatchObject({ generatedBy: "pnpm maps", doNotEdit: true, gameBuild: "9" });
    expect(verifyTrackedMaps(root)).toEqual([]);
  });

  it("is idempotent, and removes files and worlds that are no longer listed", () => {
    const { root, dist } = setup();
    syncTrackedMaps(root, dist);
    const before = readFileSync(join(root, TRACKED_MAPS_MANIFEST), "utf8");
    syncTrackedMaps(root, dist);
    expect(readFileSync(join(root, TRACKED_MAPS_MANIFEST), "utf8")).toBe(before);
    put(join(root, TRACKED_MAPS_DIR, "a/tiles/9/9/9.webp"), "stale");
    put(join(root, TRACKED_MAPS_DIR, "gone/heightmap.png"), "old world");
    syncTrackedMaps(root, dist);
    expect(verifyTrackedMaps(root)).toEqual([]);
  });

  it("fails when a listed file is missing from dist", () => {
    const { root, dist } = setup();
    rmSync(join(dist, "maps/a/heightmap.png"));
    expect(() => syncTrackedMaps(root, dist)).toThrow(/pnpm assets/);
  });
});

describe("verifyTrackedMaps", () => {
  it("reports a missing manifest, a missing file, a resized file, a hand edit and an extra file", () => {
    const { root, dist } = setup();
    expect(verifyTrackedMaps(root)).toEqual([expect.stringContaining("pnpm maps")]);
    syncTrackedMaps(root, dist);
    rmSync(join(root, TRACKED_MAPS_DIR, "b/heightmap.png"));
    put(join(root, TRACKED_MAPS_DIR, "b/tiles/0/0/0.webp"), "tile-b-longer");
    put(join(root, TRACKED_MAPS_DIR, "a/tiles/0/0/0.webp"), "tile-aX"); // same size as "tile-a1", different content
    put(join(root, TRACKED_MAPS_DIR, "a/extra.png"), "x");
    expect(verifyTrackedMaps(root)).toEqual(
      expect.arrayContaining([
        expect.stringContaining("missing: assets/maps/b/heightmap.png"),
        expect.stringContaining("size differs: assets/maps/b/tiles/0/0/0.webp"),
        expect.stringContaining("modified by hand or stale: assets/maps/a/tiles/0/0/0.webp"),
        expect.stringContaining("not generated by the pipeline: assets/maps/a/extra.png"),
      ]),
    );
  });
});

describe("committed map assets", () => {
  it("match their manifest and cover the three worlds with a pyramid and a heightmap each", () => {
    const manifest = JSON.parse(readFileSync(TRACKED_MAPS_MANIFEST, "utf8"));
    expect(Object.keys(manifest.worlds)).toEqual(["europe", "kavkazi", "north-america"]);
    for (const w of Object.values(manifest.worlds) as Array<{ files: unknown[]; maxZoom: number }>) {
      expect(w.files.length).toBeGreaterThan(5000);
      expect(w.maxZoom).toBe(6);
    }
  });
});
