import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { applyFiles, formatPlan, hasChanges, planFiles, type GeneratedFile } from "../src/generated.js";
import { buildManifest, MANIFEST_PATH, sha256, verifyManifest } from "../src/manifest.js";
import { listDataFiles } from "../src/pipeline.js";

const tmp = () => mkdtempSync(join(tmpdir(), "wardogs-gen-"));
function put(root: string, path: string, content: string) {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
}
const file = (path: string, content: string): GeneratedFile => ({ path, content });

describe("planFiles / applyFiles", () => {
  it("classifies create, update, unchanged and delete", () => {
    const root = tmp();
    put(root, "data/same.json", "1");
    put(root, "data/changed.json", "old");
    put(root, "data/stale.json", "x");
    const files = [file("data/same.json", "1"), file("data/changed.json", "new"), file("data/new.json", "n")];
    const plan = planFiles(root, files, ["data"]);
    expect(Object.fromEntries(plan.map((e) => [e.path, e.action]))).toEqual({
      "data/changed.json": "update",
      "data/new.json": "create",
      "data/same.json": "unchanged",
      "data/stale.json": "delete",
    });
    expect(hasChanges(plan)).toBe(true);
  });

  it("applies the plan and is idempotent", () => {
    const root = tmp();
    put(root, "data/stale.json", "x");
    const files = [file("data/a/b.json", "B"), file("data/c.json", "C")];
    applyFiles(root, files, planFiles(root, files, ["data"]));
    expect(readFileSync(join(root, "data/a/b.json"), "utf8")).toBe("B");
    const again = planFiles(root, files, ["data"]);
    expect(hasChanges(again)).toBe(false);
    expect(formatPlan(again)).toMatch(/^No changes/);
  });

  it("describes a plan with counts", () => {
    const text = formatPlan([
      { path: "data/a", action: "create" },
      { path: "data/b", action: "delete" },
      { path: "data/c", action: "unchanged" },
    ]);
    expect(text).toContain("+ data/a");
    expect(text).toContain("- data/b");
    expect(text).toContain("1 to create, 0 to update, 1 to delete, 1 unchanged");
  });
});

describe("manifest", () => {
  const provenance = { gameBuild: "1", cue4parse: "abc" };
  function setup() {
    const root = tmp();
    const files = [file("data/a.json", "A"), file("data/sub/b.json", "BB")];
    const manifest = buildManifest(files, provenance);
    const all = [...files, manifest];
    applyFiles(root, all, planFiles(root, all, ["data"]));
    return root;
  }

  it("lists checksums and never lists itself", () => {
    const m = JSON.parse(buildManifest([file("data/a.json", "A")], provenance).content);
    expect(m.files).toEqual([{ path: "data/a.json", sha256: sha256("A"), bytes: 1 }]);
    expect(m.doNotEdit).toBe(true);
  });

  it("passes for untouched files", () => {
    const result = verifyManifest(setup(), listDataFiles);
    expect(result).toMatchObject({ ok: true, checked: 2 });
  });

  it("fails when a generated file is edited by hand", () => {
    const root = setup();
    writeFileSync(join(root, "data/a.json"), "edited");
    expect(verifyManifest(root, listDataFiles).problems).toEqual(["modified by hand or stale: data/a.json"]);
  });

  it("fails for a file the pipeline did not produce", () => {
    const root = setup();
    put(root, "data/extra.json", "hand-written");
    expect(verifyManifest(root, listDataFiles).problems).toEqual(["not generated by the pipeline: data/extra.json"]);
  });

  it("fails when the manifest is missing", () => {
    const result = verifyManifest(tmp(), listDataFiles);
    expect(result.ok).toBe(false);
    expect(result.problems[0]).toContain(MANIFEST_PATH);
  });
});
